function J = mpc(gMPC,pyr_c, p,h_c)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Mitochondrial Pyruvate Carrier
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
h_c = h_c * 10^(3);
Kh = 0.00005;
J = gMPC .* ( (pyr_c./(p.Mcm_pyr + pyr_c)) .*  (h_c./(h_c + Kh)) );

end