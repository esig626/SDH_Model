function dy = test_2(~,x,p,g,bb)

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Variables of the model
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

glc_c = x(1);
pyr_c = x(2);
lac_c = x(3);
nadh_c= x(4);
atp_c = x(5);
adp_c = x(6);
h_c   = x(7);
pyr_m = x(8);
nadh_m= x(9);
acoa_m= x(10);
h_m   = x(11);
cit_m = x(12);
akg_m = x(13);
atp_m = x(14);
adp_m = x(15);
suc_m = x(16);
fum_m = x(17);
mal_m = x(18);
oaa_m = x(19);
qh2_m = x(20);
cred_i= x(21);
dPsi_m= x(22);
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Explicit Variables
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

nad_c = p.nadtot_c - nadh_c;
nad_m = p.nadtot_m - nadh_m;
rsn_m = nad_m./nadh_m;
rpn_c = nadh_c./nad_c;
psn_m = adp_m/atp_m;
q_m = p.Qtot - qh2_m;
cox_i = p.Ctot - cred_i;
o22 = 2.6e-5 * g;
%dPsi_m = 160;
Psi_x = -0.65*dPsi_m;
Psi_i = 0.35*dPsi_m;
pi_m = p.pi_m;
k_m = 0.14;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Cytosolic Fluxes
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Glucose Transporter
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gGLUT = 1; % Normalisation Constant. 
Jglut = glut1(gGLUT,p);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Glycolysis Model
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gGLYC = 13835058055282163712/121280368632803425;
Jglyc = glyc(gGLYC,glc_c ,nad_c,adp_c,pyr_c,atp_c,nadh_c,p,h_c);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Monocarboxylate 4 Transporter (Lactate)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gMCT4 = 648518346341351424/7243212075608875;
Jmct4 = mct4(gMCT4,lac_c,p);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Lactate Dehydrogenase
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gLDH = 5188146770730811392/915430128602150375;
Jldh = ldh(gLDH,pyr_c,nadh_c,nad_c,lac_c,p,h_c);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Mitochondrial Pyruvate Carrier
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gMPC = 32997/49625; 
Jmpc = mpc(gMPC,pyr_c, p,h_c) * 1;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Cellular ATP Demand
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gATP = 36641286568286355456/720762002450399375;
Jatp = atp(gATP,atp_c,adp_c,p,h_c);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Na/H+ Exchanger 1 
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gNHE1 = 36641286568286355456/810735649012457375;
Jnhe1c = nhe1c(gNHE1,h_c,p);


%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Mitochondrial Fluxes
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%


%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Pyruvate Dehydrogenase
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gPDH = 2405517/625000;
Jpdh = pdh(gPDH,pyr_m,rsn_m,p);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Citrate Syynthase
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gCSm =356948753546774752/23417408885117125;
Jcitm = CSm(gCSm,acoa_m,oaa_m,p);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Isocitrate Dehydrogenase
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gICD =47634/3125;
Jicdh = icd(gICD, cit_m, rsn_m,p);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Alpha-Ketoglutarate Dehydrogenase
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gAKGD = 95268/3125; 
Jakgd = akgd(gAKGD,akg_m,rsn_m,psn_m,p);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Succinate Deehydrogenase (ETC - CII)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

[J1,J2]=sdh(bb,0,0,o22,h_m,q_m,qh2_m,suc_m,fum_m,p);

% Succinate oxidation rate
gSDH = 1196268651020288/127126864613234625;
Jsuc = gSDH * J1;
%solve(Jakgd == Jsuc,gSDH)

% QH2 reduction 
gQH2 =0.1779;
Jqh2 = gQH2 * J2; 

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Fumarate 
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gFUM = 3674937295934324736/406191206104888625;
Jfum = fumm(gFUM,fum_m,p);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Malate Dehydrogenase
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
gMDH = 102905318/84375;
Jmdh = mdh(gMDH,mal_m,rsn_m,rpn_c,p);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Proton Motive Force
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
dG_H = dgh(p,dPsi_m,h_m);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% ETC - CI
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
x_C1 = 153122387330596864/8276219508788375;
J_C1 = etc1(x_C1,nadh_m,nad_m,dG_H,q_m,qh2_m,h_m,p);

%solve(Jmdh + Jakgd + Jpdh == J_C1,x_C1)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% ETC - CIII
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
x_C3 = 46393490751890289084270077739532288/5651539874953727234232488159903;
J_C3 = etc3(x_C3,h_m,qh2_m,q_m,pi_m,dG_H,dPsi_m,cox_i,cred_i,p);

%solve(J_C1 + Jqh2 == J_C3,x_C3)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% ETC - CIV
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
x_C4 = 61963218215226261/247546104476283548;
J_C4 = etc4(x_C4,cred_i,cox_i,dPsi_m,dG_H,o22,h_m,p);
%solve(2 * J_C3 == 4 * J_C4,x_C4)

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% ATPsynthase
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
x_F1 = 10625680370827264/341789307421930625;
J_F1 = atpsynth(x_F1,pi_m,adp_m, atp_m, dG_H,p); 
%solve(J_F1/Jglut == 30.2, x_F1)

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Adenine nucleotide translocase
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
x_ANT = 8619889686787129344/1108999006519302125;
J_ANT = ant(x_ANT,adp_c,atp_c,Psi_i,atp_m,adp_m,Psi_x,p);
%solve(Jakgd + J_F1 == J_ANT,x_ANT)
%solve(2 * Jglyc - 2 * Jmpc - 2 * Jldh + Jatp == Jnhe1c,gNHE1)


%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Proton Leak
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

% Val = - 4*J_C1 - 2*J_C3 - 4 * J_C4;
% Val = Val * (-1);
% A = 2 * Jmpc + Jcitm + 3 * J_F1;% %+ J_Hle + J_KH;
% Val = Val - A;

% A = 2 * Jmpc + Jcitm + 3 * J_F1 + J_Hle + J_KH;
% B = - 4 * J_C1 - 2 * J_C3 - 4 * J_C4;



gHLe = 5217058990980540603194057440381/8067632935669242412400640; %;
J_Hle = Hle(gHLe,dPsi_m,h_m,p);
%solve(- Val == J_Hle ,gHLe)
%Val = 2 * Jmpc + Jcitm + 3 * J_F1 - 4 * J_C1 - 2 * J_C3 - 4 * J_C4 + J_Hle;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% H+/K+ Transporrt
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

x_KH = 17248685809987468918784/15331624026685;
J_KH = KH(x_KH,k_m,h_m,p);
%solve(- Val == J_KH ,x_KH)

% Val = 2 * Jmpc + Jcitm + 3 * J_F1 - 4 * J_C1 - 2 * J_C3 - 4 * J_C4 + J_Hle + J_KH

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% K+ Channel
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

%Vmito =  4*J_C1 + 2*J_C3 + 4 * J_C4 -  3 * J_F1 - J_ANT - J_Hle;

x_K = 7626455394726584651623746699473/60922769016635104919723211489280;
J_K = x_K*dPsi_m*(p.K_i*exp(p.F*dPsi_m/p.RT)-k_m)/(exp(p.F*dPsi_m/p.RT)-1);

%solve(J_K == Vmito,x_K)

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Proton Gradient: 
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

% 4*J_C1+2*J_C3+4*J_C4-param.n_A*J_F1-J_ANT-J_Hle-J_K
% 2 * Jmpc + Jcitm + 3 * J_F1 - 4 * J_C1 - 2 * J_C3 - 4 * J_C4 + J_Hle

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Membrane Potential
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
Vx = 4*J_C1 + 2*J_C3 + 4 * J_C4 -  3 * J_F1 - J_ANT - J_Hle - J_K;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Equations of the Model
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
h = g;

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Cytosolic Space
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
dy(1,1) = p.Volc * (Jglut - Jglyc);                    % Glucose
dy(2,1) = p.Volc * (2 * Jglyc - 2 * Jldh - 2 * Jmpc);  % Pyruvate
dy(3,1) = p.Volc * (2 * Jldh - 2 * Jmct4 * h);             % Lactate
dy(4,1) = p.Volc * (2 * Jglyc -  2 * Jldh - Jmdh);     % NADH
dy(5,1) = p.Volc * 0.65 * (2 * Jglyc - Jatp + J_ANT);  % ATP
dy(6,1) = p.Volc * 0.65 * (Jatp - 2 * Jglyc - J_ANT);  % ADP
dy(7,1) = p.Volc * (2 * Jglyc - 2 * Jmpc - 2 * Jldh + Jatp - Jnhe1c); % H+
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Mitochondrial Matrix
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
dy(8,1) = p.Volm * (2 * Jmpc - Jpdh);         	% Pyruvate 
dy(9,1) = p.Volm * (Jmdh + Jakgd + Jpdh - J_C1);% NADH
dy(10,1)= p.Volm * (Jpdh - Jcitm);             	% AcetylCoA
dy(11,1)= p.Volm * (2 * Jmpc + Jcitm + 3 * J_F1 - 4 * J_C1 - 2 * J_C3 - 4 * J_C4 + J_Hle + J_KH);                     % H+
dy(12,1)= p.Volm * (Jcitm - Jicdh);          	% Citrate
dy(13,1)= p.Volm * (Jicdh - Jakgd);         	% aKG
dy(14,1)= p.Volm * (Jakgd + J_F1 - J_ANT);      % ATP
dy(15,1)= p.Volm * (- J_F1 - Jakgd +  J_ANT);	% ADP
dy(16,1)= p.Volm * (Jakgd - Jsuc);              % Succinate
dy(17,1)= p.Volm * (Jsuc - Jfum);               % Fumarate
dy(18,1)= p.Volm * (Jfum - Jmdh);               % Malate
dy(19,1)= p.Volm * (Jmdh - Jcitm);              % OAA
dy(20,1)= p.Volm * (J_C1 + Jqh2 - J_C3);        % QH2
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Intermembrane Space
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
dy(21,1)= (p.Volm/10) * (2*J_C3 - 4*J_C4);      % Cytocrome-C_red
dy(22,1)= Vx/(0.1 * p.C_im);                            % Membrane Potential

end



