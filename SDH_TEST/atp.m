function J = atp(gATP,atp_c,adp_c,p,h_c)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% ATP Demand
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
h_c = h_c * 10^(3);
Kh = 0.00005;
J = gATP * ((atp_c/(atp_c + p.KRSn_2GAP)) - (adp_c/( adp_c + 9)) * (h_c/(h_c + Kh)) );
end